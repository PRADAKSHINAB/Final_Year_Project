"""
research/datasets/visdrone.py
==============================
VisDrone-DET 2019 COCO-format dataset loader for Faster R-CNN.

Expected directory structure
(as created by research/prepare_dataset.py):

  Train:
    Dataset/VisDrone2019-DET-train/VisDrone2019-DET-train/
      images/          (6471 .jpg files)
      annotations/
        instances_train.json   (generated by prepare_dataset.py)

  Val:
    Dataset/VisDrone2019-DET-val/
      images/          (500 .jpg files)
      annotations/
        instances_val.json     (generated by prepare_dataset.py)

VisDrone-DET categories (10 classes, 1-indexed in COCO JSON):
    1: pedestrian, 2: people, 3: bicycle, 4: car, 5: van,
    6: truck, 7: tricycle, 8: awning-tricycle, 9: bus, 10: motor

TRANSFORM BUG FIX (v2 API):
  torchvision.transforms.v2 transforms (RandomIoUCrop, RandomZoomOut, etc.)
  require images wrapped as tv_tensors.Image and bounding boxes wrapped as
  tv_tensors.BoundingBoxes. Passing plain float tensors causes:
    TypeError: RandomIoUCrop() requires input sample to contain tensor or
               PIL images and bounding boxes.
  Fix: wrap inside __getitem__ using the dict-based sample API with
       SanitizeBoundingBoxes to auto-filter labels when boxes are removed.

Notes:
- VisDrone ignores category 0 (ignored regions) - excluded in prepare_dataset.py.
- Very small boxes (w<=2 or h<=2) are filtered in prepare_dataset.py.
- The dataset is highly imbalanced: pedestrian+people ~60-70% of instances.
- Images are loaded as uint8, converted to float32 [0,1] AFTER transforms.
"""
from __future__ import annotations

import random
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

import torch
import torchvision.tv_tensors as tv_tensors
from pycocotools.coco import COCO
from torch.utils.data import DataLoader, Dataset, Subset
from torchvision.io import read_image
from torchvision.transforms import v2 as T


# ──────────────────────────────────────────────────────────────────────────────
# Class names
# ──────────────────────────────────────────────────────────────────────────────
VISDRONE_CLASSES = [
    "pedestrian", "people", "bicycle", "car", "van",
    "truck", "tricycle", "awning-tricycle", "bus", "motor",
]

VISDRONE_CLASS_TO_IDX = {name: i + 1 for i, name in enumerate(VISDRONE_CLASSES)}


# ──────────────────────────────────────────────────────────────────────────────
# Dataset
# ──────────────────────────────────────────────────────────────────────────────

class VisDroneDataset(Dataset):
    """
    COCO-format VisDrone-DET 2019 dataset.

    Boxes are returned in [x1, y1, x2, y2] XYXY format, float32.
    Labels are 1-indexed (background = 0 is NOT in annotations).
    Images are float32 in [0, 1] range, shape [3, H, W].

    Args:
        root:          Path to split root (contains images/ and annotations/).
        split:         "train" or "val".
        transforms:    torchvision.transforms.v2 Compose pipeline or None.
                       Applied via the dict-based tv_tensors API internally.
        min_box_area:  Minimum box area in pixels (default 4 = 2×2).
    """

    def __init__(
        self,
        root: Path,
        split: str,
        transforms: Optional[Any] = None,
        min_box_area: float = 4.0,
    ) -> None:
        self.root         = Path(root)
        self.split        = split
        self.transforms   = transforms
        self.min_box_area = min_box_area

        ann_path = self.root / "annotations" / f"instances_{split}.json"
        if not ann_path.exists():
            raise FileNotFoundError(
                f"Annotation file not found: {ann_path}\n"
                f"Run:  python research/prepare_dataset.py --yes\n"
                f"to convert VisDrone TXT annotations to COCO JSON."
            )

        self.coco      = COCO(str(ann_path))
        self.ids       = sorted(self.coco.getImgIds())
        self._img_dir  = self.root / "images"

    def __len__(self) -> int:
        return len(self.ids)

    # ── Target loading ─────────────────────────────────────────────────────

    def _load_target(self, img_id: int, width: int, height: int) -> Dict:
        ann_ids = self.coco.getAnnIds(imgIds=[img_id])
        anns    = self.coco.loadAnns(ann_ids)

        boxes:    List[List[float]] = []
        labels:   List[int]         = []
        areas:    List[float]       = []
        iscrowd:  List[int]         = []

        for ann in anns:
            x, y, w, h = ann["bbox"]
            x1 = max(x, 0.0)
            y1 = max(y, 0.0)
            x2 = min(x + w, float(width))
            y2 = min(y + h, float(height))
            if (x2 - x1) <= 1 or (y2 - y1) <= 1:
                continue
            area = (x2 - x1) * (y2 - y1)
            if area < self.min_box_area:
                continue
            boxes.append([x1, y1, x2, y2])
            labels.append(int(ann["category_id"]))
            areas.append(float(area))
            iscrowd.append(int(ann.get("iscrowd", 0)))

        if not boxes:
            # Faster R-CNN can handle empty images; provide dummy to avoid crash
            boxes   = [[0.0, 0.0, 1.0, 1.0]]
            labels  = [0]
            areas   = [1.0]
            iscrowd = [0]

        return {
            "boxes":    torch.as_tensor(boxes,   dtype=torch.float32),
            "labels":   torch.as_tensor(labels,  dtype=torch.int64),
            "image_id": torch.as_tensor([img_id], dtype=torch.int64),
            "area":     torch.as_tensor(areas,   dtype=torch.float32),
            "iscrowd":  torch.as_tensor(iscrowd, dtype=torch.int64),
        }

    # ── Item loading ───────────────────────────────────────────────────────

    def __getitem__(self, idx: int) -> Tuple[torch.Tensor, Dict]:
        img_id   = self.ids[idx]
        meta     = self.coco.loadImgs([img_id])[0]
        img_path = self._img_dir / meta["file_name"]

        # Load as uint8 [3, H, W] — required by v2 PhotometricDistort
        image    = read_image(str(img_path))   # uint8
        _, H, W  = image.shape
        target   = self._load_target(img_id, W, H)

        if self.transforms is not None:
            image, target = self._apply_transforms(image, target, H, W)
        else:
            # No transforms: just normalize to float [0, 1]
            image = image.float() / 255.0

        return image, target

    # ── Transform dispatch ─────────────────────────────────────────────────

    def _apply_transforms(
        self,
        image: torch.Tensor,   # uint8 [3, H, W]
        target: Dict,
        H: int,
        W: int,
    ) -> Tuple[torch.Tensor, Dict]:
        """
        Apply torchvision.transforms.v2 pipeline correctly.

        Wraps image → tv_tensors.Image, boxes → tv_tensors.BoundingBoxes,
        passes a dict so SanitizeBoundingBoxes can auto-filter labels when
        RandomIoUCrop / RandomZoomOut remove boxes.

        Returns:
            image:  float32 [3, H', W'] in [0, 1]
            target: dict with updated boxes (float32 XYXY), labels (int64),
                    area (float32), iscrowd (int64), image_id (int64)
        """
        boxes  = target["boxes"]   # [N, 4] float32 XYXY
        labels = target["labels"]  # [N]    int64

        # ── 1. Wrap as tv_tensors ──────────────────────────────────────────
        img_tv = tv_tensors.Image(image)                     # uint8 wrapper
        boxes_tv = tv_tensors.BoundingBoxes(
            boxes,
            format=tv_tensors.BoundingBoxFormat.XYXY,
            canvas_size=(H, W),
        )

        # ── 2. Build sample dict ──────────────────────────────────────────
        #    SanitizeBoundingBoxes will filter 'labels' automatically because
        #    it looks for the "labels" key in the same container as BoundingBoxes.
        sample = {
            "image":  img_tv,
            "boxes":  boxes_tv,
            "labels": labels,
        }

        # ── 3. Apply transforms ───────────────────────────────────────────
        sample = self.transforms(sample)

        # ── 4. Extract results ────────────────────────────────────────────
        img_out    = sample["image"]   # tv_tensors.Image or Tensor
        boxes_out  = sample["boxes"]   # tv_tensors.BoundingBoxes or Tensor
        labels_out = sample["labels"]  # Tensor, already filtered

        # Unwrap tv_tensors to plain Tensor
        if isinstance(img_out, tv_tensors.Image):
            img_out = img_out.data
        if isinstance(boxes_out, tv_tensors.BoundingBoxes):
            boxes_out = boxes_out.data

        # ── 5. Normalize image to float32 [0, 1] ─────────────────────────
        if img_out.dtype == torch.uint8:
            img_out = img_out.float() / 255.0
        # If ToDtype(scale=True) was used, already float32 [0,1]

        # ── 6. Ensure correct dtypes ──────────────────────────────────────
        boxes_out  = boxes_out.float()
        labels_out = labels_out.long()

        # ── 7. Recompute area from new boxes ─────────────────────────────
        if len(boxes_out) > 0:
            # Filter degenerate or negative width/height boxes after transformation
            w_diff = boxes_out[:, 2] - boxes_out[:, 0]
            h_diff = boxes_out[:, 3] - boxes_out[:, 1]
            valid_mask = (w_diff > 1.0) & (h_diff > 1.0)
            
            if valid_mask.any():
                boxes_out  = boxes_out[valid_mask]
                labels_out = labels_out[valid_mask]
                area_out   = (boxes_out[:, 2] - boxes_out[:, 0]) * (boxes_out[:, 3] - boxes_out[:, 1])
                iscrowd_out = torch.zeros(len(boxes_out), dtype=torch.int64)
            else:
                boxes_out   = torch.tensor([[0.0, 0.0, 1.0, 1.0]], dtype=torch.float32)
                labels_out  = torch.zeros(1, dtype=torch.int64)
                area_out    = torch.ones(1, dtype=torch.float32)
                iscrowd_out = torch.zeros(1, dtype=torch.int64)
        else:
            # All boxes removed by crop — add dummy box with positive width & height to avoid crash
            boxes_out   = torch.tensor([[0.0, 0.0, 1.0, 1.0]], dtype=torch.float32)
            labels_out  = torch.zeros(1, dtype=torch.int64)
            area_out    = torch.ones(1, dtype=torch.float32)
            iscrowd_out = torch.zeros(1, dtype=torch.int64)

        return img_out, {
            "boxes":    boxes_out,
            "labels":   labels_out,
            "image_id": target["image_id"],
            "area":     area_out.float(),
            "iscrowd":  iscrowd_out,
        }

    def get_image_info(self, idx: int) -> Dict:
        """Return COCO metadata for a given index (useful for visualization)."""
        return self.coco.loadImgs([self.ids[idx]])[0]


# ──────────────────────────────────────────────────────────────────────────────
# Transforms
# ──────────────────────────────────────────────────────────────────────────────

def get_train_transforms(img_size: int) -> T.Compose:
    return T.Compose([
        T.RandomHorizontalFlip(p=0.5),
        T.RandomPhotometricDistort(p=0.8),
        T.RandomZoomOut(
            fill={tv_tensors.Image: (0, 0, 0)},
            side_range=(1.0, 2.5),
            p=0.3,
        ),
        T.RandomIoUCrop(min_scale=0.4, max_scale=1.0, min_aspect_ratio=0.5),
        T.SanitizeBoundingBoxes(min_size=2.0),
        T.Resize((img_size, img_size), antialias=True),
        T.ToDtype({tv_tensors.Image: torch.float32, "others": None}, scale=True),
    ])


def get_val_transforms(img_size: int) -> T.Compose:
    """Validation preprocessing: resize + normalize only (no augmentation)."""
    return T.Compose([
        T.Resize((img_size, img_size), antialias=True),
        T.ToDtype({tv_tensors.Image: torch.float32, "others": None}, scale=True),
    ])


# ──────────────────────────────────────────────────────────────────────────────
# DataLoader builder
# ──────────────────────────────────────────────────────────────────────────────

def collate_fn(batch: list) -> Tuple[list, list]:
    images, targets = zip(*batch)
    return list(images), list(targets)


def build_dataloaders(
    dataset_root: Path,
    img_size: int,
    batch_size: int,
    num_workers: int,
    subset_fraction: float = 1.0,
    seed: int = 42,
    train_root: Optional[Path] = None,
    val_root: Optional[Path] = None,
) -> Tuple[DataLoader, DataLoader, COCO]:
    """
    Build train + val DataLoaders for VisDrone.

    Args:
        dataset_root:     Used if train_root / val_root not specified.
                          See config for the expected layout.
        img_size:         Target image size (square).
        batch_size:       Batch size.
        num_workers:      DataLoader worker processes.
        subset_fraction:  Fraction of training data (for debug mode).
        seed:             Random seed for reproducibility.
        train_root:       Override root for train split.
        val_root:         Override root for val split.

    Returns:
        (train_loader, val_loader, val_coco_api)
    """
    _train_root = Path(train_root) if train_root else Path(dataset_root)
    _val_root   = Path(val_root)   if val_root   else Path(dataset_root)

    train_ds = VisDroneDataset(
        _train_root, "train",
        transforms=get_train_transforms(img_size),
    )
    val_ds = VisDroneDataset(
        _val_root, "val",
        transforms=get_val_transforms(img_size),
    )

    if 0.0 < subset_fraction < 1.0:
        rng       = random.Random(seed)
        n_train   = max(1, int(len(train_ds) * subset_fraction))
        train_idx = rng.sample(range(len(train_ds)), n_train)
        train_ds  = Subset(train_ds, train_idx)

    train_loader = DataLoader(
        train_ds,
        batch_size=batch_size,
        shuffle=True,
        num_workers=num_workers,
        collate_fn=collate_fn,
        pin_memory=True,
        drop_last=True,
    )
    val_loader = DataLoader(
        val_ds,
        batch_size=batch_size,
        shuffle=False,
        num_workers=num_workers,
        collate_fn=collate_fn,
        pin_memory=True,
    )

    val_coco = (val_ds.coco
                if hasattr(val_ds, "coco")
                else val_ds.dataset.coco)

    return train_loader, val_loader, val_coco
